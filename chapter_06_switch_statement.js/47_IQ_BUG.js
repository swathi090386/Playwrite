let fruit = "banana";

switch (fruit) {
    case "apple":
        console.log("This is an apple.");
    case "banana":
        console.log("This is a banana.");
    case "orange":
        console.log("This is an orange.");
    default:
        console.log("Unknown fruit.");
}

// Output:
// This is a banana.
// This is an orange.
// Unknown fruit.