// && - AND Operator
// || - OR Operator
// ! - NOT Operator

// Logical Operators: &&, ||, !

let a = true;
let b = false;

console.log(a && b); // false (both must be true) AND Operator
console.log(a || b); // true (at least one is true) OR Operator
console.log(!a); // false (negation of true)
console.log(!b); // true (negation of false)



