let x = 10;
if (x > 5)
    console.log("x is big"); // Output: x is big
if (x < 20) 
    console.log("x is small"); // single line if statement without curly braces // Output: x is small

if (x >= 5) 
    console.log("x is not less than 5"); // Output: x is not less than 5

if (x <= 20) 
    console.log("x is not greater than 20"); // Output: x is not greater than 20

if (x == 10)
    console.log("x is exactly 10"); // Output: x is exactly 10

if (x === 10)
    console.log("x is exactly 10 (strict equality)"); // Output: x is exactly 10 (strict equality)

if (x !== 15)
    console.log("x is not 15"); // Output: x is not 15

